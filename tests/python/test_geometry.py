    def test_lod2_bin(self):
        data = LOD2.read_bytes()
        magic, ver, n, zero = struct.unpack_from("<4sIII", data, 0)
        self.assertEqual((magic, ver, zero), (b"ZL2B", 1, 0))
        self.assertEqual(len(data), 16 + n * 18 + n + (-(16 + n * 19) % 4))
        self.assertEqual(len(data) % 4, 0)
        self.assertLess(len(data), 2.7e6, "about 2.5 MB budget (architecture §4.1)")
        pos = struct.unpack_from("<%dh" % (9 * n), data, 16)
        cls = data[16 + 18 * n:16 + 19 * n]
        ys = pos[1::3]
        self.assertGreaterEqual(min(ys), 0)                                  # decimetres above ground
        self.assertLess(max(ys), 1200)                                       # < 120 m (tallest ~98 m)
        xs, zs = pos[0::3], pos[2::3]
        self.assertLess(max(math.hypot(x, z) for x, z in zip(xs[::97], zs[::97])), 6000)   # ~500 m radius + a part
        self.assertTrue(set(cls) <= {0, 8, 19, 22})


