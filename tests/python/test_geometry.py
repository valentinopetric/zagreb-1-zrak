@unittest.skipUnless(ENV.exists(), "src/data/env.json not built")
class TestEnvSchema(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.raw = ENV.read_bytes()
        cls.env = json.loads(cls.raw)

    def test_keys_and_size(self):
        for k in ("meta", "buildings", "roads", "tram", "rail", "trees", "green", "water", "paved", "heating",
                  "pois", "labels", "station", "morph"):
            self.assertIn(k, self.env)
        self.assertLess(len(self.raw), 1.5e6, "architecture §4.1 target")
        m = self.env["meta"]
        self.assertEqual(m["frame"]["kx"], SITE["frame"]["kx"])
        for s in ("zg3d", "osm", "dtm"):
            self.assertIn("fetched", m["sources"][s])
        self.assertGreater(m["sources"]["zg3d"]["parts"], 3000)
        self.assertTrue(any("OpenStreetMap" in a for a in m["attribution"]))
        self.assertTrue(any("ZG3D" in a for a in m["attribution"]))

    def assert_ring(self, p, what):
        self.assertGreaterEqual(len(p), 3, what)
        self.assertNotEqual(p[0], p[-1], what + ": repeated end point")
        for x, z in p:
            self.assertLessEqual(abs(x), 900, what)
            self.assertLessEqual(abs(z), 900, what)
            self.assertAlmostEqual(x * 10, round(x * 10), places=6, msg=what + ": 0.1 m rounding")

    def test_buildings(self):
        ids = set()
        for b in self.env["buildings"]:
            self.assert_ring(b["p"], b["id"])
            self.assertGreaterEqual(b["b"], 0)
            self.assertGreaterEqual(b["h"], 1.0)
            self.assertGreater(b["h"], b["b"])
            self.assertTrue(b["b"] == 0 or b["b"] >= 1.0, "bases below 1 m are 0")
            self.assertIn(b["k"], ("zg3d", "osm"))
            self.assertIsInstance(b["s"], int)
            self.assertTrue(b["id"].startswith(b["k"] + ":"))
            self.assertEqual(b["s"] == 0, b["k"] == "osm")
            self.assertNotIn(b["id"], ids)
            ids.add(b["id"])
            self.assertNotEqual(b["id"], f"osm:w{SITE['station']['osm_way']}", "container excluded")
        years = {b["s"] for b in self.env["buildings"] if b["k"] == "zg3d"}
        self.assertTrue({2008, 2019, 2022} <= years)

    def test_roads(self):
        groups = set()
        for r in self.env["roads"]:
            self.assertGreaterEqual(len(r["p"]), 2)
            self.assertIn(r["c"], range(6))
            self.assertIn(r["o"], (-1, 0, 1))
            self.assertIsInstance(r["l"], int)
            self.assertGreater(r["w"], 0)
            self.assertIn(r["g"], ("A", "B", "C", None))
            self.assertEqual(r["g"] is None, r["c"] == 5)
            self.assertEqual(r["aadt"] > 0, r["g"] is not None)
            if r["g"] == "A":
                self.assertEqual(r["n"], "Ulica grada Vukovara")
            if r["g"] == "B":
                self.assertIn(r["n"], be.NAMES_B)
            if r["c"] < 5 and not (abs(r["p"][0][1]) <= 40 and r["n"] == "Miramarska cesta"):
                self.assertAlmostEqual(r["w"], round(r["l"] * be.LANE_W, 1), places=6)
            groups.add(r["g"])
