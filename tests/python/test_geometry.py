class TestBinaryPatches(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.page = json.loads((FIX / "geo_zg3d_sample.json").read_text(encoding="utf-8"))
        cls.feats = {f["attributes"]["OBJECTID"]: f for f in cls.page["features"]}

    def decode(self, oid):
        return fz.decode_binary_patches(self.feats[oid]["geometry"]["binaryPatches"])

    def test_first_ring_part(self):
        pp = self.decode(60300)
        self.assertEqual(len(pp), 76)
        self.assertTrue(all(t == fz.FIRST_RING and len(r) == 5 for t, r in pp))
        lon, lat, z = pp[0][1][0]
        self.assertAlmostEqual(lon, 15.965487273, places=8)
        self.assertAlmostEqual(lat, 45.805778222, places=8)
        self.assertAlmostEqual(z, 115.8966, places=3)

    def test_part_types(self):
        self.assertEqual({t for t, _ in self.decode(351605)}, {fz.TRIANGLE_FAN})
        self.assertEqual({t for t, _ in self.decode(353639)}, {fz.OUTER_RING, fz.INNER_RING})
        self.assertEqual([(t, len(r)) for t, r in self.decode(352697)], [(fz.OUTER_RING, 5)])

    def test_z_within_attributes(self):
        for oid, f in self.feats.items():
            a = f["attributes"]
            zs = [z for _, r in self.decode(oid) for _, _, z in r]
            self.assertGreaterEqual(min(zs), a["Z_Min"] - 0.01, oid)
            self.assertLessEqual(max(zs), a["Z_Max"] + 0.01, oid)

    def test_coordinates_in_scene_box(self):
        s, w, n, e = bbox_latlon(SITE["extent"]["scene_half_m"] + 50)
        for oid in self.feats:
            for _, r in self.decode(oid):
                for lon, lat, _ in r:
                    self.assertTrue(w <= lon <= e and s <= lat <= n)

    def test_triangulated_surface_area(self):
        """The triangles cover every face exactly: their area equals the Newell areas of the rings (outer
        minus inner rings), and never exceeds the part's closed-surface attribute SArea (+1 % for the local
        frame's scale; ZG3D multipatches often have no bottom face, which SArea counts)."""
        for oid, f in self.feats.items():
            loc = [(t, [(*xz(lat, lon), Z) for lon, lat, Z in r]) for t, r in self.decode(oid)]
            patches = [(t, [(x, Z, z) for x, z, Z in r]) for t, r in loc]
            tris = fz.triangulate_patches(patches)
            area = sum(fz.tri_area_3d(*t) for t in tris)
            exp = 0.0
            for t, r in patches:
                if t in (fz.TRIANGLE_FAN,):
                    exp += sum(fz.tri_area_3d(r[0], r[i], r[i + 1]) for i in range(1, len(r) - 1))
                    continue
                a = 0.5 * math.sqrt(sum(c * c for c in fz.newell_normal(fz._clean_ring(r))))
                exp += -a if t in (fz.INNER_RING, fz.RING) else a
            self.assertAlmostEqual(area, exp, delta=1e-6 * exp, msg=oid)
            self.assertLess(area, 1.01 * f["attributes"]["SArea"], oid)

    def test_query_urls(self):
        u = fz.query_url("lod2", 500, 750)
        for s in ("outSR=4326", "inSR=4326", "multipatchOption=embedMaterials", "returnZ=true", "resultOffset=500"):
            self.assertIn(s, u)
        u = fz.query_url("fp", 0, 750)
        self.assertIn("multipatchOption=xyFootprint", u)
        self.assertIn("f=geojson", u)


