    def test_macdonald_reproduces_critic(self):
        d, z0 = be.macdonald(0.246, 0.193, 14.2)          # critic §1.10: d 6.8 m, z0 1.47 m
        self.assertAlmostEqual(d, 6.8, delta=0.05)
        self.assertAlmostEqual(z0, 1.47, delta=0.03)
        d, z0 = be.macdonald(0.22, 0.17, 12.8)            # sector N: d 5.6, z0 1.35
        self.assertAlmostEqual(d, 5.6, delta=0.1)
        self.assertAlmostEqual(z0, 1.35, delta=0.05)

    def test_region_stats_synthetic(self):
        """A single 10 m x 10 m x 20 m block: lambda_p, Hbar and lambda_f by hand."""
        g = be.Grid(30.0, 1.0)
        H = be.paint_heights(g, [{"p": [(-5, -5), (5, -5), (5, 5), (-5, 5)], "h": 20.0}])
        s = be.region_stats(g, H, 0.0, "disc", 20.0)
        area = s["cells"]
        self.assertAlmostEqual(s["lambda_p"], 100 / area, delta=0.01)
        self.assertAlmostEqual(s["Hbar"], 20.0)
        self.assertAlmostEqual(s["lambda_f"], 10 * 20 / area, delta=0.01)
        s45 = be.region_stats(g, H, 45.0, "disc", 20.0)
        self.assertAlmostEqual(s45["lambda_f"] / s["lambda_f"], math.sqrt(2), delta=0.12)

