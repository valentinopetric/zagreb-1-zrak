TINY_E0, TINY_N0, TINY_PX = 575690.0, 5072360.0, 20.0   # NW corner of the tiny tile (EPSG:3045), near ZAGREB-1
TINY_W, TINY_H = 5, 4
TINY_NODATA = (3, 4)                                     # (row, col) set to -9999


def tiny_value(r: int, c: int) -> float:
    """A plane h = 100 + 0.5 c - 0.25 r, so bilinear interpolation is exact."""
    return 100.0 + 0.5 * c - 0.25 * r


def tiny_tiff(contiguous: bool = True) -> bytes:
    """A minimal GeoTIFF with the RH_ELEV_107 layout. contiguous=False writes the strips in reverse order."""
    rows = []
    for r in range(TINY_H):
        vals = [(-9999.0 if (r, c) == TINY_NODATA else tiny_value(r, c)) for c in range(TINY_W)]
        rows.append(struct.pack("<%dd" % TINY_W, *vals))
    geokeys = [1, 1, 0, 3, 1024, 0, 1, 1, 1025, 0, 1, 1, 3072, 0, 1, 3045]
    entries = [  # (tag, type, count, payload bytes)
        (256, 3, 1, struct.pack("<H", TINY_W)), (257, 3, 1, struct.pack("<H", TINY_H)),
        (258, 3, 1, struct.pack("<H", 64)), (259, 3, 1, struct.pack("<H", 1)), (262, 3, 1, struct.pack("<H", 1)),
        (273, 4, TINY_H, None), (277, 3, 1, struct.pack("<H", 1)), (278, 3, 1, struct.pack("<H", 1)),
        (279, 4, TINY_H, struct.pack("<%dI" % TINY_H, *([TINY_W * 8] * TINY_H))),
        (284, 3, 1, struct.pack("<H", 1)), (339, 3, 1, struct.pack("<H", 3)),
        (33550, 12, 3, struct.pack("<3d", TINY_PX, TINY_PX, 0.0)),
        (33922, 12, 6, struct.pack("<6d", 0.0, 0.0, 0.0, TINY_E0, TINY_N0, 0.0)),
        (34735, 3, len(geokeys), struct.pack("<%dH" % len(geokeys), *geokeys)),
        (42113, 2, 6, b"-9999\0"),
    ]
    n = len(entries)
    ifd_size = 2 + 12 * n + 4
    data_off = 8 + ifd_size
    blobs, offsets = b"", {}
    for tag, _typ, _cnt, payload in entries:
        if payload is not None and len(payload) > 4:
            offsets[tag] = data_off + len(blobs)
            blobs += payload + (b"\0" if len(payload) % 2 else b"")
    strip_arr_off = data_off + len(blobs)
    blobs += b"\0" * (4 * TINY_H)
    strips_off = data_off + len(blobs)
    order = list(range(TINY_H)) if contiguous else list(reversed(range(TINY_H)))
    strip_offsets = [0] * TINY_H
    strips = b""
    for r in order:
        strip_offsets[r] = strips_off + len(strips)
        strips += rows[r]
    blobs = blobs[:strip_arr_off - data_off] + struct.pack("<%dI" % TINY_H, *strip_offsets) + blobs[strip_arr_off - data_off + 4 * TINY_H:]
    ifd = struct.pack("<H", n)
    for tag, typ, cnt, payload in entries:
        if tag == 273:
            ifd += struct.pack("<HHII", tag, typ, cnt, strip_arr_off)
        elif len(payload) > 4:
            ifd += struct.pack("<HHII", tag, typ, cnt, offsets[tag])
        else:
            ifd += struct.pack("<HHI", tag, typ, cnt) + payload.ljust(4, b"\0")
    ifd += struct.pack("<I", 0)
    return b"II" + struct.pack("<HI", 42, 8) + ifd + blobs + strips


def bytes_reader(data: bytes) -> fd.Reader:
    def read(offset: int, length: int) -> bytes:
        out = data[offset:offset + length]
        if len(out) != length:
            raise IOError("short read")
        return out
    return read


