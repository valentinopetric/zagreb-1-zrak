class TestParityVectors(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.raw = json.loads(FIX.read_text(encoding="utf-8"))
        cls.cases = dec(cls.raw["cases"])

    def test_embedded_copy_in_models_test_js_is_identical(self):
        js = JS_TEST.read_text(encoding="utf-8")
        a = js.index("const MT_PARITY = ") + len("const MT_PARITY = ")
        b = js.index(M.PARITY_END)
        body = js[a:b].rstrip().rstrip(";")
        self.assertEqual(json.loads(body), self.raw, "run python3 tools/aqmodel.py --write-parity")

    def test_every_section_has_a_runner(self):
        for sec in self.cases:
            if not sec.startswith("fallback"):
                self.assertIn(sec, RUN, sec)

    def test_sections_reproduce(self):
        n = 0
        for sec, cases in self.cases.items():
            if sec.startswith("fallback"):
                continue
            for k, c in enumerate(cases):
                close(self, RUN[sec](c["in"]), c["out"], f"{sec}#{k}")
                n += 1
        self.assertGreater(n, 900)

    def test_fallback_reproduces(self):
        env = self.cases["fallback_env"][0]["in"]["env"]
        fb = M.FallbackModel(env)
        close(self, {"center": list(fb.center), "n": fb.src["n"], "canyons": fb.canyons}, self.cases["fallback_env"][0]["out"], "env")
        for k, c in enumerate(self.cases["fallback_receptor"]):
            close(self, fb.receptor(c["in"]["dir"], c["in"]["cls"]), c["out"], f"receptor#{k}")
        for k, c in enumerate(self.cases["fallback_slice"]):
            close(self, fb.slice(c["in"]["dir"], c["in"]["cls"], c["in"]["height"], c["in"]["grid"]), c["out"], f"slice#{k}")


class TestMeteo(unittest.TestCase):
    def test_kernel_sums_to_one_and_calm_is_uniform(self):
        for u in (0.5, 1.0, 2.0, 6.0):
            for d in (0, 33, 180, 359.5):
                w = M.direction_weights(d, u)
                self.assertAlmostEqual(sum(w), 1.0, places=12)
                self.assertLessEqual(abs(M.ang_diff(M.DIRS16[w.index(max(w))], d)), 11.25 + 1e-9)
        self.assertEqual(M.direction_weights(10, 0.49), [1 / 16] * 16)
        w = M.direction_weights(90, 3)
        self.assertAlmostEqual(w[5] / w[4], math.exp(-0.5), places=12)

    def test_stability_tables(self):
        self.assertEqual(M.stability_class(1, 950, 50), "A")
        self.assertEqual(M.stability_class(4, 950, 50), "B")
        self.assertEqual(M.stability_class(7, 950, 50), "C")
        self.assertEqual(M.stability_class(2.5, 700, 50), "B")
        self.assertEqual(M.stability_class(4, 300, 50), "C")
        self.assertEqual(M.stability_class(1, 100, 50), "D")
        self.assertEqual(M.stability_class(1, 0, 30), "F")
        self.assertEqual(M.stability_class(4, 0, 30), "E")
        self.assertEqual(M.stability_class(2.5, 0, 70), "E")
        self.assertEqual(M.stability_class(4, 0, 70), "D")
        self.assertEqual(M.stability_class(1, 0, 100), "D")
        for c, L in {"A": -9.6, "B": -22, "C": -135, "E": 106, "F": 22}.items():   # critic §1.13
            self.assertAlmostEqual(M.obukhov_length(c, 0.5), L, delta=abs(L) * 0.03)
        self.assertEqual(M.obukhov_length("D"), math.inf)
        self.assertAlmostEqual(M.turb_params("D", 1.4, 8, 14)["ustar_hat"], 0.162, delta=0.001)   # physics §6.2

    def test_local_time_matches_zoneinfo(self):
        try:
            from zoneinfo import ZoneInfo
            tz = ZoneInfo("Europe/Zagreb")
        except Exception:  # pragma: no cover - tzdata not installed
            self.skipTest("zoneinfo/tzdata not available")
        t = dt.datetime(2024, 1, 1, tzinfo=dt.timezone.utc)
        while t < dt.datetime(2026, 1, 1, tzinfo=dt.timezone.utc):
            p = M.local_parts(t.timestamp() * 1000)
            ref = (t - dt.timedelta(hours=1)).astimezone(tz)
            self.assertEqual((p["year"], p["month"], p["day"], p["hour"], p["dow"]),
                             (ref.year, ref.month, ref.day, ref.hour, ref.weekday()), t.isoformat())
            t += dt.timedelta(hours=7)

    def test_solar_elevation(self):
        self.assertAlmostEqual(M.solar_elevation("2025-03-20T11:04:00Z"), 90 - 45.8, delta=0.6)
        self.assertAlmostEqual(M.solar_elevation("2025-06-21T11:02:00Z"), 90 - 45.8 + 23.44, delta=0.6)
        self.assertLess(M.solar_elevation("2025-06-21T23:00:00Z"), 0)


class TestChemistry(unittest.TestCase):
    def test_limits(self):
        k, J = M.k_no_o3(15), M.j_no2(600)
        r = M.no2_chemistry(0, 0, 0, 50, 60, J, k)
        self.assertAlmostEqual(r["no2"], 0, places=9)
        self.assertAlmostEqual(r["o3"], 50, places=9)
        r = M.no2_chemistry(500, 20, 50, 10, math.inf, 0, k, 0.1)             # O3-limited titration
        X = 10 / M.PPB["o3"] + 20 / M.PPB["no2"] + 50 / M.PPB["no2"]
        self.assertAlmostEqual(r["no2"], X * M.PPB["no2"], places=9)
        self.assertAlmostEqual(r["o3"], 0, places=9)
        r = M.no2_chemistry(120, 25, 40, 45, math.inf, J, k)                  # PSS: k (N-x)(X-x) = J x
        N, x = r["nox"] / M.PPB["no2"], r["no2"] / M.PPB["no2"]
        self.assertAlmostEqual(k * (N - x) * (r["ox"] - x), J * x, delta=1e-9 * J * x)
        self.assertAlmostEqual(M.k_no_o3(15), 4.19e-4, delta=0.02e-4)         # critic §1.13
        self.assertAlmostEqual(M.j_no2(800) / 1.05, 8.7e-3, delta=0.05e-3)
        self.assertAlmostEqual(M.PPB["no2"], 1.9125, places=4)

    def test_rmse_on_the_2025_sample(self):
        cases = dec(json.loads(FIX.read_text(encoding="utf-8"))["cases"]).get("chem_sample") or []
        if len(cases) < 250:
            self.skipTest("chem_sample empty (processed tables were absent when the vectors were generated)")
        obs = [c["in"]["obs"] for c in cases]
        mod = [RUN["chem_sample"](c["in"])["no2"] for c in cases]
        m = M.metrics(obs, mod)
        self.assertLess(m["RMSE"], 6.5)       # critic §1.2: 5.0 on all 2025 hours
        self.assertGreater(m["R"], 0.94)
        self.assertLess(abs(m["FB"]), 0.05)

    @unittest.skipUnless((PROCESSED / "iszz_hourly.csv.gz").exists() and (PROCESSED / "ifs_hourly.csv.gz").exists(),
                         "processed tables not present")
    def test_rmse_on_all_2025_hours(self):
        obs, met = CAL.load_processed(PROCESSED / "iszz_hourly.csv.gz", PROCESSED / "ifs_hourly.csv.gz",
                                      "2025-01-01T01:00:00Z", "2026-01-01T00:00:00Z")
        o, p = [], []
        for t, v in obs.items():
            m = met.get(t)
            if not m or not all(k in v and math.isfinite(v[k]) for k in ("z1.nox", "z1.no2", "z4.nox", "z4.no2", "z4.o3")):
                continue
            if not (math.isfinite(m["sw"]) and math.isfinite(m["t2"])):
                continue
            r = M.no2_chemistry(v["z1.nox"] - v["z4.nox"], v["z4.no2"], v["z4.nox"], v["z4.o3"], 60, M.j_no2(m["sw"]),
                                M.k_no_o3(m["t2"]), 0.10)
            o.append(v["z1.no2"])
            p.append(r["no2"])
        mm = M.metrics(o, p)
        self.assertGreater(mm["n"], 7000)
        self.assertAlmostEqual(mm["RMSE"], 5.0, delta=0.4)     # critic §1.2: 5.0; this data: 5.1
        self.assertGreater(mm["R"], 0.955)


