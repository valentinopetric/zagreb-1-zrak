def dec(v):
    """Undo the JSON encoding of ±Infinity / NaN used in the parity file."""
    if v == "Infinity":
        return math.inf
    if v == "-Infinity":
        return -math.inf
    if v == "NaN":
        return math.nan
    if isinstance(v, list):
        return [dec(x) for x in v]
    if isinstance(v, dict):
        return {k: dec(x) for k, x in v.items()}
    return v


def close(tc: unittest.TestCase, a, b, path: str = "", rel: float = 1e-6) -> None:
    """Deep comparison with the tolerance of models.test.js (1e-6 relative + 1e-12 absolute)."""
    if isinstance(b, bool) or b is None or isinstance(b, str):
        tc.assertEqual(a, b, path)
    elif isinstance(b, (int, float)):
        if math.isnan(b):
            tc.assertTrue(math.isnan(a), f"{path}: expected NaN, got {a}")
        elif math.isinf(b):
            tc.assertEqual(a, b, path)
        else:
            tc.assertLessEqual(abs(a - b), rel * abs(b) + 1e-12, f"{path}: {a} vs {b}")
    elif isinstance(b, list):
        tc.assertEqual(len(a), len(b), f"{path}: length")
        for i, (x, y) in enumerate(zip(a, b)):
            close(tc, x, y, f"{path}[{i}]", rel)
    elif isinstance(b, dict):
        for k in b:
            close(tc, a[k], b[k], f"{path}.{k}", rel)
    else:  # pragma: no cover
        tc.fail(f"{path}: unsupported type {type(b)}")


