class TestFallback(unittest.TestCase):
    def test_long_crosswind_road_matches_the_line_source_formula(self):
        """A 4 km road perpendicular to the wind: Σ point sources = W/(√(2π) σz) · (vertical terms), class D."""
        env = {"roads": [{"p": [[-2000, 50], [2000, 50]], "g": "A", "aadt": 10000, "o": 0, "w": 0.001}], "buildings": []}
        fb = M.FallbackModel(env, radius=3000)
        g = fb.receptor(180, "D")["gamma"][0]        # wind from the south: the road is 50 m upwind of the receptor
        x = 50.0
        _, szb = M.briggs("D", x)
        sz = math.sqrt(M.FB_SZ0 ** 2 + szb ** 2)
        zr, hs = M.RECEPTOR[1], M.FB_HS_ROAD
        V = math.exp(-(zr - hs) ** 2 / (2 * sz * sz)) + math.exp(-(zr + hs) ** 2 / (2 * sz * sz))
        self.assertAlmostEqual(g, V / (math.sqrt(2 * math.pi) * sz), delta=0.01 * g)

    def test_linear_in_aadt_and_zero_upwind(self):
        env = {"roads": [{"p": [[-300, 40], [300, 40]], "g": "A", "aadt": 20000, "w": 10}], "buildings": []}
        a = M.FallbackModel(env).receptor(200, "D")["gamma"][0]
        env["roads"][0]["aadt"] = 40000
        b = M.FallbackModel(env).receptor(200, "D")["gamma"][0]
        self.assertAlmostEqual(b, 2 * a, delta=1e-12)
        self.assertEqual(M.FallbackModel(env).receptor(0, "D")["gamma"][0], 0.0)   # wind from N: road downwind

    def test_canyon_term(self):
        fb = M.FallbackModel(M.synthetic_env())
        self.assertIsNotNone(fb.canyons[1], "the B street between two slabs is a canyon")
        self.assertIsNone(fb.canyons[0])
        lee = fb.receptor(270, "D")["canyon"][1]     # wind from W: receptor (x=0) on the upwind side of B (x≈20)
        self.assertGreater(lee, 0)
        self.assertEqual(fb.receptor(0, "D")["canyon"][1], 0.0)   # parallel wind: no cross-canyon vortex

    def test_real_env_speed(self):
        path = ROOT / "src" / "data" / "env.json"
        env = json.loads(path.read_text(encoding="utf-8"))
        import time
        t0 = time.perf_counter()
        fb = M.FallbackModel(env)
        r = fb.receptor(45, "D")
        self.assertLess(time.perf_counter() - t0, 30)
        self.assertTrue(all(math.isfinite(v) and v >= 0 for v in r["gamma"]))


class TestCalibrate(unittest.TestCase):
    def _synthetic(self, beta=3.0, U0=1.3, n=600):
        import random
        rnd = random.Random(7)
        hours = []
        for i in range(n):
            u = rnd.uniform(0.2, 5)
            S = rnd.uniform(1e-6, 4e-5)
            hours.append({"S": S, "u": u, "obs": 1e6 * beta * S / math.sqrt(u * u + U0 * U0), "month": 202501 + (i % 12)})
        return hours

    def test_fit_recovers_parameters_with_and_without_numpy(self):
        hours = self._synthetic()
        saved = CAL.np
        try:
            for mod in (saved, None):
                CAL.np = mod
                p = CAL.fit(hours)
                self.assertAlmostEqual(p["beta"], 3.0, delta=0.02)
                self.assertAlmostEqual(p["U0"], 1.3, delta=0.051)
        finally:
            CAL.np = saved

    def test_write_if_changed_is_idempotent(self):
        with tempfile.TemporaryDirectory() as d:
            p = Path(d) / "c.json"
            CAL.write_if_changed(p, {"a": 1.5, "b": [1, 2]})
            first = p.read_text()
            CAL.write_if_changed(p, {"a": 1.5, "b": [1, 2]})
            self.assertEqual(first, p.read_text())
            CAL.write_if_changed(p, {"a": 2.0})
            self.assertEqual(json.loads(p.read_text())["a"], 2.0)

    def test_baseline_on_a_pure_profile(self):
        hours = []
        for i in range(24 * 60):
            h = i % 24
            u = 1 + (i * 7 % 13) / 4
            hours.append({"obs": (10 + h) / math.sqrt(u * u + CAL.BASELINE_U0 ** 2), "u": u, "dir": (i * 37) % 360,
                          "dtype": "weekday", "lhour": h})
        b = CAL.baseline_fit(hours)
        pred = CAL.baseline_predict(b, hours)
        m = M.metrics([h["obs"] for h in hours], pred)
        self.assertLess(m["NMSE"], 1e-9)


