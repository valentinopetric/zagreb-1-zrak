def easter(Y: int) -> tuple[int, int]:
    """Gregorian Easter Sunday (Meeus), (month, day)."""
    a, b, c = Y % 19, Y // 100, Y % 100
    d, e = b // 4, b % 4
    f = (b + 8) // 25
    g = (b - f + 1) // 3
    h = (19 * a + b - d - g + 15) % 30
    i, k = c // 4, c % 4
    l = (32 + 2 * e + 2 * i - h - k) % 7
    m = (a + 11 * h + 22 * l) // 451
    x = h + l - 7 * m + 114
    return x // 31, x % 31 + 1


def is_holiday(year: int, month: int, day: int) -> bool:
    if (month, day) in EM_HOLIDAYS_FIXED:
        return True
    em, ed = easter(year)
    e = dt.date(year, em, ed)
    x = dt.date(year, month, day)
    return x in (e + dt.timedelta(days=1), e + dt.timedelta(days=60))


def day_type(p: dict) -> str:
    if p["dow"] == 6 or is_holiday(p["year"], p["month"], p["day"]):
        return "sunday"
    return "saturday" if p["dow"] == 5 else "weekday"


def traffic_factor(t: Any, month: bool = True) -> float:
    p = local_parts(t)
    typ = day_type(p)
    TP = TRAFFIC_PROFILES
    fd = TP["day"][6] if typ == "sunday" else TP["day"][p["dow"]]
    return 24 * TP["hour"][typ][p["hour"]] * fd * (TP["month"][p["month"] - 1] if month else 1)


