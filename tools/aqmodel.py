def increment(gamma: Sequence[float], age: Sequence[float], q: dict, u10: float, beta: float, U0: float) -> dict:
    """ΔC = 1e6 β Σ q Γ / U_eff and τ = Σ q A / (U_eff Σ q Γ) for one source (increment() with an explicit cal)."""
    qs = [q.get("A", 0) or 0, q.get("B", 0) or 0, q.get("C", 0) or 0, q.get("D", 0) or 0]
    U = u_eff(u10, U0)
    by = [0.0] * 4
    num = den = 0.0
    for k in range(4):
        by[k] += 1e6 * beta * qs[k] * (gamma[k] or 0) / U
        num += beta * qs[k] * (age[k] or 0) / (U * U)
        den += beta * qs[k] * (gamma[k] or 0) / U
    return {"total": by[0] + by[1] + by[2] + by[3], "byGroup": by, "tau": num / den if den > 0 else CHEM_TAU_DEFAULT}


def metrics(obs: Sequence[float], mod: Sequence[float], floor: float = 1.0) -> dict:
    """Chang & Hanna (2004) statistics, same conventions as metrics() in model.js."""
    o, p = [], []
    for a, b in zip(obs, mod):
        if finite(a) and finite(b):
            o.append(float(a))
            p.append(float(b))
    n = len(o)
    if not n:
        return {k: math.nan for k in ("FB", "NMSE", "MG", "VG", "FAC2", "NAD", "R", "RMSE", "meanObs", "meanMod")} | {"n": 0}
    so = sp = 0.0
    for i in range(n):
        so += o[i]
        sp += p[i]
    mo, mp = so / n, sp / n
    se = sa = lg = lg2 = f2 = cov = vo = vp = 0.0
    for i in range(n):
        d = o[i] - p[i]
        se += d * d
        sa += abs(d)
        lo, lp = math.log(max(o[i], floor)), math.log(max(p[i], floor))
        lg += lo - lp
        lg2 += (lo - lp) * (lo - lp)
        ratio = max(p[i], floor) / max(o[i], floor)
        if 0.5 <= ratio <= 2:
            f2 += 1
        cov += (o[i] - mo) * (p[i] - mp)
        vo += (o[i] - mo) * (o[i] - mo)
        vp += (p[i] - mp) * (p[i] - mp)
    return {"FB": (mo - mp) / (0.5 * (mo + mp)) if mo + mp else math.nan,
            "NMSE": (se / n) / (mo * mp) if mo * mp else math.nan,
            "MG": math.exp(lg / n), "VG": math.exp(lg2 / n), "FAC2": f2 / n,
            "NAD": (sa / n) / (mo + mp) if mo + mp else math.nan,
            "R": cov / math.sqrt(vo * vp) if vo > 0 and vp > 0 else math.nan,
            "n": n, "RMSE": math.sqrt(se / n), "meanObs": mo, "meanMod": mp}


MOD_MQI = {"no2": (0.24, 200, 0.20), "o3": (0.18, 120, 0.79), "pm10": (0.28, 50, 0.25), "pm25": (0.36, 25, 0.50)}


def mqi(obs: Sequence[float], mod: Sequence[float], pollutant: str) -> float:
    P = MOD_MQI.get(pollutant)
    if not P:
        return math.nan
    Ur, RV, al = P
    se = su = 0.0
    n = 0
    for a, b in zip(obs, mod):
        if not (finite(a) and finite(b)):
            continue
        d = a - b
        se += d * d
        su += Ur * Ur * ((1 - al * al) * a * a + al * al * RV * RV)
        n += 1
    return math.sqrt(se / n) / (2 * math.sqrt(su / n)) if n else math.nan


def gamma_table(fb: FallbackModel, classes: Sequence[str] = MET_CLASSES) -> dict:
    """{cls: [16 dirs] -> receptor dict} of the fallback, the Python analogue of the LUT."""
    return {c: [fb.receptor(d, c) for d in DIRS16] for c in classes}


def smooth_gamma(rows: Sequence[dict], dir_deg: float, u10: float) -> dict:
    """Kernel-weighted Γ, A and queue over the 16 run directions (ReceptorModel.gammaAt, one source)."""
    w = direction_weights(dir_deg, u10)
    out = {"gamma": [0.0] * 4, "age": [0.0] * 4, "queue": [0.0] * 4}
    for j, wj in enumerate(w):
        if not (wj > 0):
            continue
        r = rows[j]
        for k in range(4):
            out["gamma"][k] += wj * (r["gamma"][k] or 0)
            out["age"][k] += wj * (r["age"][k] or 0)
            if "queue" in r and r["queue"]:
                out["queue"][k] += wj * r["queue"][k]
    return out


def load_env(path: Path = SRC_DATA / "env.json") -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


