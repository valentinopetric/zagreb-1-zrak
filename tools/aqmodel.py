# ================================================================== core.js helpers
def wrap360(a: float) -> float:
    return ((a % 360) + 360) % 360


def ang_diff(a: float, b: float) -> float:
    d = wrap360(a - b)
    return d - 360 if d > 180 else d


def clamp(x: float, a: float, b: float) -> float:
    return min(b, max(a, x))


def finite(x: Any) -> bool:
    return isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x)


def point_in_poly(x: float, z: float, poly: Sequence[Sequence[float]]) -> bool:
    inside = False
    j = len(poly) - 1
    for i in range(len(poly)):
        xi, zi = poly[i][0], poly[i][1]
        xj, zj = poly[j][0], poly[j][1]
        if (zi > z) != (zj > z) and x < ((xj - xi) * (z - zi)) / (zj - zi) + xi:
            inside = not inside
        j = i
    return inside


def bounds(poly) -> dict:
    return {"x0": min(p[0] for p in poly), "x1": max(p[0] for p in poly),
            "z0": min(p[1] for p in poly), "z1": max(p[1] for p in poly)}


def seg_dist(x: float, z: float, ax: float, az: float, bx: float, bz: float) -> float:
    dx, dz = bx - ax, bz - az
    L2 = dx * dx + dz * dz or 1e-12
    s = clamp(((x - ax) * dx + (z - az) * dz) / L2, 0, 1)
    return math.hypot(x - ax - dx * s, z - az - dz * s)


def to_ms(t: Any) -> float:
    """Epoch ms from a number, datetime or ISO string ('2025-01-14T08:00Z')."""
    if isinstance(t, (int, float)):
        return float(t)
    if isinstance(t, dt.datetime):
        return (t if t.tzinfo else t.replace(tzinfo=UTC)).timestamp() * 1000
    s = str(t).replace("Z", "+00:00")
    d = dt.datetime.fromisoformat(s)
    return (d if d.tzinfo else d.replace(tzinfo=UTC)).timestamp() * 1000


