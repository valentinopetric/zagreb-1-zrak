DIRS16 = [i * 22.5 for i in range(16)]


def dir_index16(deg: float) -> int:
    if not finite(deg):
        return 0
    # JS Math.round rounds .5 up; floor(x + 0.5) reproduces it for x >= 0
    return int(math.floor(wrap360(deg) / 22.5 + 0.5)) % 16


def _last_sunday_utc(year: int, month: int) -> float:
    """01:00 UTC of the last Sunday of `month` (1..12), epoch ms (met_lastSundayUTC)."""
    nxt = dt.datetime(year + (month == 12), month % 12 + 1, 1, 1, tzinfo=UTC)
    last = nxt - dt.timedelta(days=1)
    back = (last.weekday() + 1) % 7                     # days since Sunday
    return (last - dt.timedelta(days=back)).timestamp() * 1000


def local_parts(t: Any, hour_start: bool = True) -> dict:
    """Europe/Zagreb calendar of the hour start (met_localParts): EU summer-time rule, Directive 2000/84/EC."""
    ms = to_ms(t) - (3600e3 if hour_start else 0)
    y = dt.datetime.fromtimestamp(ms / 1000, tz=UTC).year
    dst = _last_sunday_utc(y, 3) <= ms < _last_sunday_utc(y, 10)
    off = 2 if dst else 1
    d = dt.datetime.fromtimestamp((ms + off * 3600e3) / 1000, tz=UTC)
    return {"year": d.year, "month": d.month, "day": d.day, "hour": d.hour, "dow": d.weekday(), "offset": off}


def solar_elevation(t: Any, lat: float = SITE["station"]["lat"], lon: float = SITE["station"]["lon"]) -> float:
    """NOAA General Solar Position Calculations (Spencer 1971 series), degrees, no refraction."""
    ms = to_ms(t)
    d = dt.datetime.fromtimestamp(ms / 1000, tz=UTC)
    y = d.year
    leap = (y % 4 == 0 and y % 100 != 0) or y % 400 == 0
    doy = math.floor((ms - dt.datetime(y, 1, 1, tzinfo=UTC).timestamp() * 1000) / 86400e3) + 1
    hour = d.hour + d.minute / 60 + d.second / 3600
    g = (2 * math.pi / (366 if leap else 365)) * (doy - 1 + (hour - 12) / 24)
    eqtime = 229.18 * (0.000075 + 0.001868 * math.cos(g) - 0.032077 * math.sin(g)
                       - 0.014615 * math.cos(2 * g) - 0.040849 * math.sin(2 * g))
    decl = (0.006918 - 0.399912 * math.cos(g) + 0.070257 * math.sin(g) - 0.006758 * math.cos(2 * g)
            + 0.000907 * math.sin(2 * g) - 0.002697 * math.cos(3 * g) + 0.00148 * math.sin(3 * g))
    tst = hour * 60 + eqtime + 4 * lon
    ha = (tst / 4 - 180) * DEG
    cz = math.sin(lat * DEG) * math.sin(decl) + math.cos(lat * DEG) * math.cos(decl) * math.cos(ha)
    return 90 - math.acos(clamp(cz, -1, 1)) / DEG


def shortwave_estimate(elev_deg: float, cloud_pct: float | None) -> float:
    """Holtslag & van Ulden (1983) clear-sky irradiance with cloud reduction (met_shortwaveEstimate)."""
    if not (elev_deg > 0):
        return 0.0
    N = clamp((cloud_pct if finite(cloud_pct) else 50) / 100, 0, 1)
    return max(0.0, (990 * math.sin(elev_deg * DEG) - 30) * (1 - 0.75 * math.pow(N, 3.4)))


