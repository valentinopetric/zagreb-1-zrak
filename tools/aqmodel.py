CHEM_TAU_DEFAULT = 60.0


def no2_chemistry(nox_inc: float = 0, no2_bg: float = 0, nox_bg: float = 0, o3_bg: float = 0,
                  tau: float = CHEM_TAU_DEFAULT, J: float = 0, k: float | None = None, f_no2: float = MD["f_no2"]) -> dict:
    """Riccati finite-reaction-time NO-NO2-O3 scheme with conserved oxidant (no2Chemistry)."""
    if k is None:
        k = k_no_o3(15)
    P = PPB
    dN = max(0.0, nox_inc or 0) / P["no2"]
    Nb = max(0.0, nox_bg or 0) / P["no2"]
    xb = max(0.0, no2_bg or 0) / P["no2"]
    ob = max(0.0, o3_bg or 0) / P["o3"]
    N = Nb + dN
    X = ob + xb + f_no2 * dN
    x0 = xb + f_no2 * dN
    if not (tau > 0) or not (k > 0):
        x = x0
    else:
        A = max(0.0, J or 0) / k
        s = N + X + A
        D = math.sqrt(max(s * s - 4 * N * X, 1e-12))
        x1, x2 = 0.5 * (s - D), 0.5 * (s + D)
        if tau == math.inf:
            x = x1
        else:
            den = x0 - x2
            if abs(den) < 1e-12:
                x = x1
            else:
                E = ((x0 - x1) / den) * math.exp(-k * D * tau)
                x = (x1 - x2 * E) / (1 - E)
    x = clamp(x, 0, min(N, X))
    return {"no2": x * P["no2"], "no": (N - x) * P["no"], "o3": (X - x) * P["o3"], "nox": N * P["no2"], "ox": X}


