def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0], formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write-parity", action="store_true", help="regenerate the Python↔JS parity vectors")
    ap.add_argument("--receptor", nargs=2, metavar=("DIR", "CLS"), help="fallback Γ at ZAGREB-1 for one direction/class")
    ap.add_argument("--hour", help="print q_k and the fallback increment for one hour (ISO, hour-ending UTC)")
    ap.add_argument("--u10", type=float, default=1.7)
    ap.add_argument("--dir", type=float, default=45)
    ap.add_argument("--sw", type=float)
    ap.add_argument("--cc", type=float, default=50)
    ap.add_argument("--t2", type=float, default=10)
    ap.add_argument("--beta", type=float, default=1.0)
    a = ap.parse_args(argv)
    if a.write_parity:
        write_parity()
    if a.receptor:
        fb = FallbackModel(load_env())
        print(json.dumps({"center": fb.center, "points": fb.src["n"], "canyons": fb.canyons,
                          "receptor": fb.receptor(float(a.receptor[0]), a.receptor[1])}, indent=1))
    if a.hour:
        t = to_ms(a.hour)
        cls = stability_class(a.u10, a.sw, a.cc, t)
        fb = FallbackModel(load_env())
        rows = [fb.receptor(d, cls) for d in DIRS16]
        ga = smooth_gamma(rows, a.dir, a.u10)
        q = group_strengths("nox", t, {}, "auto")
        inc = increment(ga["gamma"], ga["age"], q, a.u10, a.beta, MD["U0"])
        print(json.dumps({"class": cls, "local": local_parts(t), "trafficFactor": traffic_factor(t), "q": q,
                          "gamma": ga["gamma"], "increment": inc}, indent=1))
    if not (a.write_parity or a.receptor or a.hour):
        ap.print_help()
    return 0


