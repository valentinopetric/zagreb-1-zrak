def chem_sample(step: int = 26) -> list[dict]:
    """Real 2025 hours for the chemistry parity case and the RMSE test: ZAGREB-1 NOx/NO2, ZAGREB-4 NOx/NO2/O3,
    IFS SW and T2 from data/processed (empty if the tables are absent). Every `step`-th complete hour."""
    import csv
    import gzip
    iszz, ifs = ROOT / "data" / "processed" / "iszz_hourly.csv.gz", ROOT / "data" / "processed" / "ifs_hourly.csv.gz"
    if not (iszz.exists() and ifs.exists()):
        log.warning("chem_sample: processed tables missing, section left empty")
        return []
    obs: dict[str, dict] = {}
    with gzip.open(iszz, "rt", encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            if r["t_utc_end"][:4] == "2025":
                obs.setdefault(r["t_utc_end"], {})[("z1." if r["station"] == "155" else "z4.") + r["param"]] = float(r["value"])
    met: dict[str, dict] = {}
    with gzip.open(ifs, "rt", encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            if r["t_utc_end"][:4] == "2025" and r["sw"] and r["t2"]:
                met[r["t_utc_end"]] = {"sw": float(r["sw"]), "t2": float(r["t2"])}
    need = ("z1.nox", "z1.no2", "z4.nox", "z4.no2", "z4.o3")
    keys = [t for t in sorted(obs) if t in met and all(k in obs[t] for k in need)]
    out = []
    for t in keys[::step]:
        o, m = obs[t], met[t]
        inp = {"noxInc": o["z1.nox"] - o["z4.nox"], "no2Bg": o["z4.no2"], "noxBg": o["z4.nox"], "o3Bg": o["z4.o3"],
               "tau": CHEM_TAU_DEFAULT, "sw": m["sw"], "t2": m["t2"], "fNO2": MD["f_no2"], "obs": o["z1.no2"], "t": t}
        r = no2_chemistry(inp["noxInc"], inp["no2Bg"], inp["noxBg"], inp["o3Bg"], inp["tau"], j_no2(m["sw"]), k_no_o3(m["t2"]),
                          inp["fNO2"])
        out.append({"in": inp, "out": r})
    return out


def write_parity() -> None:
    data = build_parity()
    text = json.dumps(data, separators=(",", ":"), ensure_ascii=False)
    PARITY_JSON.parent.mkdir(parents=True, exist_ok=True)
    _atomic_write(PARITY_JSON, text + "\n")
    js = MODELS_TEST_JS.read_text(encoding="utf-8")
    a, b = js.find(PARITY_BEGIN), js.find(PARITY_END)
    if a < 0 or b < a:
        raise SystemExit(f"markers not found in {MODELS_TEST_JS}")
    js = js[:a + len(PARITY_BEGIN)] + "\nconst MT_PARITY = " + text + ";\n" + js[b:]
    _atomic_write(MODELS_TEST_JS, js)
    n = sum(len(v) for v in data["cases"].values())
    log.info("parity: %d cases in %d sections -> %s and %s", n, len(data["cases"]), PARITY_JSON, MODELS_TEST_JS)


def _atomic_write(path: Path, text: str) -> None:
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix=".tmp-", suffix=path.suffix)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(text)
    os.chmod(tmp, 0o644)
    os.replace(tmp, path)


