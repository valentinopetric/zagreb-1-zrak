def stability_class(u10: float | None, sw: float | None = None, cloud: float | None = None, t: Any = None) -> str:
    """SRDT by day, Turner by night (stabilityClass)."""
    if not finite(u10):
        return "D"
    G = sw
    if not finite(G):
        G = 0.0 if t is None else shortwave_estimate(solar_elevation(to_ms(t) - 1800e3), cloud)
    if G > 0:
        row = 0 if G >= 925 else 1 if G >= 675 else 2 if G >= 175 else 3
        col = 0 if u10 < 2 else 1 if u10 < 3 else 2 if u10 < 5 else 3 if u10 < 6 else 4
        return MET_SRDT[row][col]
    cc = cloud if finite(cloud) else 50
    if cc >= 95:
        return "D"
    if cc > 40:
        return "F" if u10 < 1.9 else "E" if u10 < 3.4 else "D"
    return "F" if u10 < 3.4 else "E" if u10 < 5.5 else "D"


def stability_group(cls: str) -> str:
    if cls in ("AC", "D", "EF"):
        return cls
    return "AC" if cls in ("A", "B", "C") else "EF" if cls in ("E", "F") else "D"


def met_class(c: str) -> str:
    return MET_GROUP_CLASS.get(c) or (c if c in MET_CLASSES else "D")


def obukhov_length(cls: str, z0: float = MD["z0_m"]) -> float:
    a, b = MET_GOLDER[met_class(cls)]
    inv = a + b * math.log10(min(z0, 0.5))
    return math.inf if abs(inv) < 1e-12 else 1 / inv


def mixing_height(cls: str = "D", blh: float | None = None, mode: str = "auto", h_min: float | None = None) -> float:
    base = blh if finite(blh) else MET_BLH_MEDIAN[met_class(cls)]
    m = str(mode)
    floor = (MET_H_RAW_FLOOR if m == "nwp" else 315 if m == "315" else 100 if m == "100"
             else (h_min if finite(h_min) else MD["h_min_m"]))
    return max(base, floor)


def u_eff(u10: float | None, U0: float = MD["U0"]) -> float:
    u = max(0.0, u10) if finite(u10) else 0.0
    return math.sqrt(u * u + U0 * U0)


def direction_weights(from_deg: float | None, u10: float | None, dirs: Sequence[float] = DIRS16) -> list[float]:
    n = len(dirs)
    if not (finite(u10) and u10 >= 0.5) or not finite(from_deg):
        return [1 / n] * n
    s = min(60.0, 22.5 * max(1.0, 2 / u10))
    tmp = []
    for d0 in dirs:
        d = ang_diff(from_deg, d0)
        tmp.append(math.exp(-(d * d) / (2 * s * s)))
    tot = 0.0
    for v in tmp:
        tot += v
    return [v / tot for v in tmp]


def vector_mean_wind(obs: Iterable[dict]) -> dict:
    ue = vn = s = 0.0
    n = 0
    for o in obs or []:
        if not o or not finite(o.get("u")) or not finite(o.get("dir")):
            continue
        ue += -o["u"] * math.sin(o["dir"] * DEG)
        vn += -o["u"] * math.cos(o["dir"] * DEG)
        s += o["u"]
        n += 1
    if not n:
        return {"u": math.nan, "dir": math.nan, "scalar": math.nan, "n": 0}
    ue /= n
    vn /= n
    return {"u": math.hypot(ue, vn), "dir": wrap360(math.atan2(-ue, -vn) / DEG), "scalar": s / n, "n": n}


def psi_m(zeta: float) -> float:
    if zeta < 0:
        x = math.pow(1 - 16 * zeta, 0.25)
        return 2 * math.log((1 + x) / 2) + math.log((1 + x * x) / 2) - 2 * math.atan(x) + math.pi / 2
    return -5 * min(zeta, 1)


def phi_h(zeta: float) -> float:
    return 1 / math.sqrt(1 - 16 * zeta) if zeta < 0 else 1 + 5 * min(zeta, 1)


def ustar_hat(L: float, z0: float = MD["z0_m"], d: float = MD["d_m"], z0r: float = MD["z0r_m"],
              zb: float = MD["zb_m"], kappa: float = MD["kappa"]) -> float:
    iL = 1 / L if finite(L) and L != 0 else 0.0
    P = psi_m
    usr = kappa / (math.log(10 / z0r) - P(10 * iL) + P(z0r * iL))
    ub = (usr / kappa) * (math.log(zb / z0r) - P(zb * iL) + P(z0r * iL))
    return kappa * ub / (math.log((zb - d) / z0) - P((zb - d) * iL) + P(z0 * iL))


def u_hat(z: float, turb: dict) -> float:
    zz = max(z, turb["Hbar"], turb["d"] + 2 * turb["z0"])
    iL = turb.get("invL") or 0.0
    return (turb["ustar_hat"] / turb["kappa"]) * (math.log((zz - turb["d"]) / turb["z0"]) - psi_m((zz - turb["d"]) * iL)
                                                  + psi_m(turb["z0"] * iL))


def k_hat_mo(z: float, turb: dict) -> float:
    ze = max(z, turb["Hbar"])
    if ze >= turb["h_eff"]:
        return 0.0
    zh = ze - turb["d"]
    lid = 1 - ze / turb["h_eff"]
    return turb["kappa"] * turb["ustar_hat"] * zh / phi_h(zh * (turb.get("invL") or 0.0)) * lid * lid


def turb_params(cls: str, z0: float | None = None, d: float | None = None, Hbar: float | None = None,
                h_eff: float | None = None, h_min: float | None = None) -> dict:
    c = met_class(cls)
    zz0 = z0 if finite(z0) else MD["z0_m"]
    dd = d if finite(d) else MD["d_m"]
    H = Hbar if finite(Hbar) else MD["Hbar_m"]
    L = obukhov_length(c, zz0)
    return {"cls": c, "group": stability_group(c), "L": L, "invL": 1 / L if finite(L) else 0.0,
            "ustar_hat": ustar_hat(L, zz0, dd, MD["z0r_m"], MD["zb_m"], MD["kappa"]),
            "h_eff": h_eff if finite(h_eff) else mixing_height(c, h_min=h_min),
            "z0": zz0, "d": dd, "Hbar": H, "Sct": MD["Sct"], "lambda": MD["lambda_m"], "kmin": MD["kmin_m"],
            "kappa": MD["kappa"], "z0r": MD["z0r_m"], "zb": MD["zb_m"]}


def j_no2(sw: float | None) -> float:
    G = max(0.0, sw) if finite(sw) else 0.0
    return max(0.0, 1.05 * (1.47e-5 * G - 4.84e-9 * G * G))


def k_no_o3(temp_c: float | None, p_hpa: float = 1013.25) -> float:
    T = (temp_c if finite(temp_c) else 15) + 273.15
    return 3.0e-12 * math.exp(-1500 / T) * (7.2429e18 * p_hpa / T) * 1e-9


