FB_RADIUS, FB_SPACING, FB_HEAT_CELL = 800.0, 4.0, 10.0
FB_HS_ROAD, FB_HS_HEAT, FB_SZ0, FB_XMIN, FB_YCUT, FB_IMAGES = 0.5, 8.0, 2.0, 0.5, 6.0, 3
FB_EXP_MAX = 40.0   # image terms below exp(-40) are skipped (speed only)
FB_CANYON_RANGE, FB_CANYON_RAY, FB_CANYON_HW, FB_OSPM_LAMBDA = 60.0, 80.0, 0.3, 0.1
FB_QUEUE = (15.0, 75.0)
FB_GROUPS = {"A": 0, "B": 1, "C": 2}
FB_SYC = {"A": 0.32, "B": 0.32, "C": 0.22, "D": 0.16, "E": 0.11, "F": 0.11}   # σyB <= c·x (cheap lateral bound)


def briggs(cls: str, x: float) -> tuple[float, float]:
    if cls in ("A", "B"):
        return 0.32 * x / math.sqrt(1 + 0.0004 * x), 0.24 * x * math.sqrt(1 + 0.001 * x)
    if cls == "C":
        return 0.22 * x / math.sqrt(1 + 0.0004 * x), 0.20 * x
    if cls == "D":
        return 0.16 * x / math.sqrt(1 + 0.0004 * x), 0.14 * x / math.sqrt(1 + 0.0003 * x)
    return 0.11 * x / math.sqrt(1 + 0.0004 * x), 0.08 * x / math.sqrt(1 + 0.0015 * x)


def _seg_x(p1, p2, p3, p4):
    d1x, d1z, d2x, d2z = p2[0] - p1[0], p2[1] - p1[1], p4[0] - p3[0], p4[1] - p3[1]
    den = d1x * d2z - d1z * d2x
    if abs(den) < 1e-12:
        return None
    s = ((p3[0] - p1[0]) * d2z - (p3[1] - p1[1]) * d2x) / den
    u = ((p3[0] - p1[0]) * d1z - (p3[1] - p1[1]) * d1x) / den
    if s < 0 or s > 1 or u < 0 or u > 1:
        return None
    return (p1[0] + s * d1x, p1[1] + s * d1z)


def _ray_hit(ox, oz, dx, dz, a, b) -> float:
    ex, ez = b[0] - a[0], b[1] - a[1]
    den = dx * ez - dz * ex
    if abs(den) < 1e-12:
        return math.inf
    tt = ((a[0] - ox) * ez - (a[1] - oz) * ex) / den
    u = ((a[0] - ox) * dz - (a[1] - oz) * dx) / den
    return tt if tt > 1e-9 and 0 <= u <= 1 else math.inf


class FallbackModel:
    """Gaussian line/area sources (Briggs urban) + OSPM-type canyon term (FallbackModel in fallback.js)."""

    def __init__(self, env: dict, radius: float = FB_RADIUS, spacing: float = FB_SPACING, heat_cell: float = FB_HEAT_CELL,
                 receptor: tuple[float, float, float] = RECEPTOR, h_min: float | None = None):
        env = env or {}
        self.radius, self.spacing, self.heat_cell = radius, spacing, heat_cell
        self.rx, self.ry, self.rz = receptor
        self.h_min = h_min if finite(h_min) else MD["h_min_m"]
        self.roads = [r for r in env.get("roads") or [] if r and r.get("g") in FB_GROUPS and (r.get("aadt") or 0) > 0
                      and r.get("p") and len(r["p"]) > 1]
        blds = env["buildings"] if env.get("buildings") is not None else [
            b for b in env.get("prisms") or [] if not (b and b.get("s") is not None and b["s"] < 0.5)]
        self.buildings = [b for b in blds if b and b.get("p") and len(b["p"]) > 2 and (b.get("h") or 0) > 0]
        self.heating = [hp for hp in env.get("heating") or [] if hp and hp.get("p") and len(hp["p"]) > 2]
        self._bb = [bounds(b["p"]) for b in self.buildings]
        self.center = self._intersection()
        self._build_sources()
        self.canyons = [self._canyon(gi) for gi in range(3)]
        self._cache: dict = {}

    def _intersection(self):
        def segs(g):
            out = []
            for rd in self.roads:
                if rd["g"] != g:
                    continue
                for i in range(len(rd["p"]) - 1):
                    a, b = rd["p"][i], rd["p"][i + 1]
                    if seg_dist(self.rx, self.rz, a[0], a[1], b[0], b[1]) < 150:
                        out.append((a, b))
            return out
        A, B = segs("A"), segs("B")
        sx = sz = 0.0
        n = 0
        for a1, a2 in A:
            for b1, b2 in B:
                p = _seg_x(a1, a2, b1, b2)
                if p:
                    sx += p[0]
                    sz += p[1]
                    n += 1
        return (sx / n, sz / n) if n else None

    def _build_sources(self) -> None:
        X, Z, W, H, S, G, Q = [], [], [], [], [], [], []
        R2 = self.radius * self.radius
        C = self.center
        for rd in self.roads:
            gi = FB_GROUPS[rd["g"]]
            a = rd["aadt"] / MD["aadt_unit"]
            w = rd.get("w") or 0
            sy0 = (w if w > 0 else 3.25 * (rd["l"] if (rd.get("l") or 0) > 0 else 2)) / 2
            o = rd.get("o") or 0
            for i in range(len(rd["p"]) - 1):
                x1, z1 = rd["p"][i][0], rd["p"][i][1]
                x2, z2 = rd["p"][i + 1][0], rd["p"][i + 1][1]
                L = math.hypot(x2 - x1, z2 - z1)
                if not (L > 0):
                    continue
                n = max(1, math.ceil(L / self.spacing))
                ds = L / n
                for k in range(n):
                    s = (k + 0.5) / n
                    px, pz = x1 + (x2 - x1) * s, z1 + (z2 - z1) * s
                    ex, ez = px - self.rx, pz - self.rz
                    if ex * ex + ez * ez > R2:
                        continue
                    qf = 0.0
                    if C and gi < 2:
                        d = math.hypot(px - C[0], pz - C[1])
                        if FB_QUEUE[0] <= d <= FB_QUEUE[1]:
                            if o == 0:
                                qf = 0.5
                            else:
                                tx, tz = o * (x2 - x1) / L, o * (z2 - z1) / L
                                qf = 1.0 if tx * (C[0] - px) + tz * (C[1] - pz) > 0 else 0.0
                    X.append(px); Z.append(pz); W.append(a * ds); H.append(FB_HS_ROAD); S.append(sy0); G.append(gi); Q.append(qf)
        c = self.heat_cell
        for hp in self.heating:
            wt = (hp["w"] if finite(hp.get("w")) else 1) * c * c
            bb = bounds(hp["p"])
            i0, i1 = math.ceil((bb["x0"] - c / 2) / c), math.floor((bb["x1"] - c / 2) / c)
            j0, j1 = math.ceil((bb["z0"] - c / 2) / c), math.floor((bb["z1"] - c / 2) / c)
            for j in range(j0, j1 + 1):
                for i in range(i0, i1 + 1):
                    px, pz = i * c + c / 2, j * c + c / 2
                    ex, ez = px - self.rx, pz - self.rz
                    if ex * ex + ez * ez > R2 or not point_in_poly(px, pz, hp["p"]):
                        continue
                    X.append(px); Z.append(pz); W.append(wt); H.append(FB_HS_HEAT); S.append(c / 2); G.append(3); Q.append(0.0)
        self.src = {"x": X, "z": Z, "w": W, "hs": H, "sy0": S, "g": G, "q": Q, "n": len(X)}

    def _wall(self, ox, oz, dx, dz):
        best, h = math.inf, 0.0
        reach = FB_CANYON_RAY
        for b, bb in zip(self.buildings, self._bb):
            if (bb["x1"] < min(ox, ox + dx * reach) - 1 or bb["x0"] > max(ox, ox + dx * reach) + 1
                    or bb["z1"] < min(oz, oz + dz * reach) - 1 or bb["z0"] > max(oz, oz + dz * reach) + 1):
                continue
            p = b["p"]
            for i in range(len(p)):
                tt = _ray_hit(ox, oz, dx, dz, p[i], p[(i + 1) % len(p)])
                if tt < best and tt <= reach:
                    best, h = tt, b["h"]
        return {"dist": best, "h": h} if best <= reach else None

    def _canyon(self, gi: int):
        best, P0, seg = math.inf, None, None
        for rd in self.roads:
            if FB_GROUPS[rd["g"]] != gi:
                continue
            for i in range(len(rd["p"]) - 1):
                ax, az = rd["p"][i][0], rd["p"][i][1]
                bx, bz = rd["p"][i + 1][0], rd["p"][i + 1][1]
                dx, dz = bx - ax, bz - az
                L2 = dx * dx + dz * dz
                if not (L2 > 0):
                    continue
                s = clamp(((self.rx - ax) * dx + (self.rz - az) * dz) / L2, 0, 1)
                px, pz = ax + dx * s, az + dz * s
                d = math.hypot(self.rx - px, self.rz - pz)
                if d < best:
                    best, P0, seg = d, (px, pz), (dx, dz, math.sqrt(L2))
        if P0 is None or best > FB_CANYON_RANGE:
            return None
        if best > 0.1:
            nx, nz = (self.rx - P0[0]) / best, (self.rz - P0[1]) / best
        else:
            nx, nz = -seg[1] / seg[2], seg[0] / seg[2]
        near, far = self._wall(P0[0], P0[1], nx, nz), self._wall(P0[0], P0[1], -nx, -nz)
        if not near or not far or near["dist"] <= best:
            return None
        Wc, Hc = near["dist"] + far["dist"], (near["h"] + far["h"]) / 2
        if Hc / Wc < FB_CANYON_HW:
            return None
        Qu = 0.0
        for rd in self.roads:
            if FB_GROUPS[rd["g"]] != gi:
                continue
            dmin = math.inf
            for i in range(len(rd["p"]) - 1):
                dmin = min(dmin, seg_dist(P0[0], P0[1], rd["p"][i][0], rd["p"][i][1], rd["p"][i + 1][0], rd["p"][i + 1][1]))
            if dmin <= max(near["dist"], far["dist"]):
                Qu += rd["aadt"] / MD["aadt_unit"]
        return {"nx": nx, "nz": nz, "W": Wc, "H": Hc, "hNear": near["h"], "hFar": far["h"], "Q": Qu, "dist": best}

    def _kernel(self, m: int, rx: float, ry: float, rz: float, bx: float, bz: float, c: str, h: float):
        S = self.src
        dx, dz = rx - S["x"][m], rz - S["z"][m]
        x = dx * bx + dz * bz
        if x <= FB_XMIN:
            return 0.0, x
        y = -dx * bz + dz * bx
        sy0 = S["sy0"][m]
        if abs(y) > FB_YCUT * (sy0 + FB_SYC[c] * x):
            return 0.0, x
        syb, szb = briggs(c, x)
        sy = math.sqrt(sy0 * sy0 + syb * syb)
        if abs(y) > FB_YCUT * sy:
            return 0.0, x
        sz = math.sqrt(FB_SZ0 * FB_SZ0 + szb * szb)
        hs, s2 = S["hs"][m], 2 * sz * sz
        V = 0.0
        nI = FB_IMAGES if sz > h / 4 else 0
        for n in range(-nI, nI + 1):
            a, b = ry - hs + 2 * n * h, ry + hs + 2 * n * h
            ea, eb = (a * a) / s2, (b * b) / s2
            if ea < FB_EXP_MAX:
                V += math.exp(-ea)
            if eb < FB_EXP_MAX:
                V += math.exp(-eb)
        return S["w"][m] / (2 * math.pi * sy * sz) * math.exp(-(y * y) / (2 * sy * sy)) * V, x

    def receptor(self, dir_deg: float, cls: str) -> dict:
        c = met_class(cls)
        key = (round(wrap360(dir_deg) * 10), c)
        if key not in self._cache:
            self._cache[key] = self._receptor(wrap360(dir_deg), c)
        r = self._cache[key]
        return {k: (list(v) if isinstance(v, list) else v) for k, v in r.items()}

    def _receptor(self, dir_deg: float, c: str) -> dict:
        out = {"gamma": [0.0] * 4, "age": [0.0] * 4, "queue": [0.0] * 4, "canyon": [0.0] * 4, "n": 0}
        h = mixing_height(c, h_min=self.h_min)
        bx, bz = -math.sin(dir_deg * DEG), math.cos(dir_deg * DEG)
        S = self.src
        for m in range(S["n"]):
            g, x = self._kernel(m, self.rx, self.ry, self.rz, bx, bz, c, h)
            if not g:
                continue
            k = S["g"][m]
            out["gamma"][k] += g
            out["age"][k] += g * x
            out["queue"][k] += g * S["q"][m]
            out["n"] += 1
        turb = turb_params(c)
        for gi in range(3):
            cy = self.canyons[gi]
            if not cy:
                continue
            bn = bx * cy["nx"] + bz * cy["nz"]
            leeward = bn < 0
            Lv = 2 * (cy["hNear"] if leeward else cy["hFar"])
            if not leeward and Lv < cy["W"]:
                continue
            Lr, Lt = min(Lv, cy["W"]), min(Lv / 2, cy["W"])
            if not (Lt > 0):
                continue
            swt = FB_OSPM_LAMBDA * u_hat(cy["H"], turb)
            gr = cy["Q"] * Lr / (cy["W"] * swt * Lt) * abs(bn)
            out["gamma"][gi] += gr
            out["age"][gi] += gr * (Lr * cy["H"]) / (swt * Lt)
            out["canyon"][gi] += gr
        return out

    def _rotated(self, dir_deg: float) -> dict:
        """Sources in wind coordinates, sorted by the along-wind coordinate (FallbackModel._rotated)."""
        bx, bz = -math.sin(dir_deg * DEG), math.cos(dir_deg * DEG)
        S = self.src
        along = [S["x"][m] * bx + S["z"][m] * bz for m in range(S["n"])]
        idx = sorted(range(S["n"]), key=lambda m: along[m])
        return {"bx": bx, "bz": bz, "n": S["n"], "a": [along[m] for m in idx],
                "c": [-S["x"][m] * bz + S["z"][m] * bx for m in idx], "w": [S["w"][m] for m in idx],
                "hs": [S["hs"][m] for m in idx], "sy0": [S["sy0"][m] for m in idx], "g": [S["g"][m] for m in idx]}

    def slice(self, dir_deg: float, cls: str, height: float, grid: dict) -> list[float]:
        """Γ on a horizontal slice, cell centres, index ((j·nx + i)·4 + k) (FallbackModel.slice)."""
        import bisect
        c = met_class(cls)
        h = mixing_height(c, h_min=self.h_min)
        x0, z0, dx, nx, nz = grid["x0"], grid["z0"], grid["dx"], grid["nx"], grid["nz"]
        res = [0.0] * (nx * nz * 4)
        R = self._rotated(wrap360(dir_deg))
        cyc = FB_SYC[c]
        for j in range(nz):
            z = z0 + (j + 0.5) * dx
            for i in range(nx):
                x = x0 + (i + 0.5) * dx
                ar, cr = x * R["bx"] + z * R["bz"], -x * R["bz"] + z * R["bx"]
                lo = bisect.bisect_left(R["a"], ar - FB_XMIN)
                acc = [0.0] * 4
                for m in range(lo):
                    xx = ar - R["a"][m]
                    if xx <= FB_XMIN:
                        continue
                    yy, sy0 = cr - R["c"][m], R["sy0"][m]
                    if abs(yy) > FB_YCUT * (sy0 + cyc * xx):
                        continue
                    syb, szb = briggs(c, xx)
                    sy = math.sqrt(sy0 * sy0 + syb * syb)
                    if abs(yy) > FB_YCUT * sy:
                        continue
                    sz = math.sqrt(FB_SZ0 * FB_SZ0 + szb * szb)
                    hs, s2 = R["hs"][m], 2 * sz * sz
                    V = 0.0
                    nI = FB_IMAGES if sz > h / 4 else 0
                    for n in range(-nI, nI + 1):
                        aa, bb = height - hs + 2 * n * h, height + hs + 2 * n * h
                        ea, eb = (aa * aa) / s2, (bb * bb) / s2
                        if ea < FB_EXP_MAX:
                            V += math.exp(-ea)
                        if eb < FB_EXP_MAX:
                            V += math.exp(-eb)
                    acc[R["g"][m]] += R["w"][m] / (2 * math.pi * sy * sz) * math.exp(-(yy * yy) / (2 * sy * sy)) * V
                o = (j * nx + i) * 4
                res[o:o + 4] = acc
        return res


